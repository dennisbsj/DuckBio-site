import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import path from 'node:path';import os from 'node:os';
import {spawnSync} from 'node:child_process';
import {randomBytes} from 'node:crypto';
import {createIdentityStore} from '../shared-auth/identity-store.mjs';
import {createOrganizationStore} from '../organization-store.mjs';

test('offline organization setup binds exact pre-existing active central administrator, without purchasing seats',async t=>{
 const dir=mkdtempSync(path.join(os.tmpdir(),'duckbio-org-cli-'));
 t.after(()=>rmSync(dir,{recursive:true,force:true}));
 const identityPath=path.join(dir,'identity.sqlite'),orgPath=path.join(dir,'private','org.sqlite');
 const identity=createIdentityStore({databasePath:identityPath});
 const token=randomBytes(32).toString('base64url');identity.configureBootstrapToken(token);
 const owner=await identity.bootstrap(token,{email:'admin@example.test',displayName:'Account Administrator',password:'Synthetic password 12345'});
 const user=await identity.createUser({email:'member@example.test',displayName:'Member',password:'Synthetic password 12345'});
 identity.close();
 const args=['--identity-db',identityPath,'--organization-db',orgPath,'--id','lab-1','--name','Synthetic Lab','--owner-id',owner.id,'--nickname','Admin'];
 const cmd=extra=>spawnSync(process.execPath,['./setup-organization.mjs',...(extra||args)],{cwd:path.resolve('workspace-server'),encoding:'utf8'});
 const denied=cmd(args.map(x=>x===owner.id?user.id:x));
 assert.equal(denied.status,1);assert.match(denied.stderr,/verified_admin_required/);
 const ok=cmd();assert.equal(ok.status,0,ok.stderr);assert.deepEqual(JSON.parse(ok.stdout),{ok:true,organizationId:'lab-1'});
 const org=createOrganizationStore({databasePath:orgPath});
 const view=org.overview('lab-1',owner.id);
 assert.deepEqual(view.apps.map(a=>a.purchased),[0,0,0,0,0,0]);
 assert.equal(view.users[0].email,'admin@example.test');
 assert.deepEqual(view.users[0].roles,{});
 assert.throws(()=>org.overview('lab-1',user.id),/access_denied/);
 org.close();
 const again=cmd();assert.equal(again.status,1);assert.match(again.stderr,/organization_exists/);
 assert(!again.stderr.includes('admin@example.test'));
});
