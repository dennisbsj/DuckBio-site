import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createPublicKey,verify as verifyEd25519} from 'node:crypto';
import {canonicalNativeOwnershipProofBytes}
 from '../shared-auth/signed-native-ownership-verifier.mjs';

// Immutable, PUBLIC synthetic fixture: generated once using an independent
// throwaway signer, with NO PRIVATE KEY committed. All values are explicit.
// Do not derive expected bytes or signatures from the Workspace helper.
const fixture=JSON.parse(readFileSync(
 new URL('./fixtures/native-ownership-v1-known-answer.json',import.meta.url),'utf8'
));
const FIELDS=Object.freeze([
 'version','keyId','purpose','nonce','appId','workspaceAccountId',
 'workspaceOrganizationId','nativeUserId','nativeOrganizationId',
 'issuedAt','expiresAt','active','ownershipVerified'
]);
const expectedPurposes=['inspect','bind','migrate'];
const expectedApps=['goflo','eel','duckman'];

function verifyStatic(proof,signature,key){
 return verifyEd25519(null,canonicalNativeOwnershipProofBytes(proof),
  key,Buffer.from(signature,'base64url'));
}

test('public known-answer vectors independently pin all v1 canonical UTF-8 bytes and Ed25519 signatures',()=>{
 assert.equal(fixture.format,'duckbio.native-ownership.v1');
 assert.equal(fixture.vectors.length,3);
 const key=createPublicKey(fixture.publicKeyPem);
 assert.equal(key.asymmetricKeyType,'ed25519');
 for(const [index,{proof,canonicalUtf8,signatureBase64url}] of
      fixture.vectors.entries()){
  assert.deepEqual(Object.keys(proof),FIELDS);
  assert.equal(proof.purpose,expectedPurposes[index]);
  assert.equal(proof.appId,expectedApps[index]);
  assert.equal(proof.version,fixture.format);
  assert.equal(proof.keyId,'synthetic-vector-key-2026');
  assert.equal(Buffer.from(proof.nonce,'base64url').length,32);
  assert.equal(proof.expiresAt-proof.issuedAt,15000);
  assert.equal(proof.active,true);
  assert.equal(proof.ownershipVerified,true);
  // This explicit expected string was NOT generated by the production helper.
  // A changed field order, number/string coercion, omission or escaping is a
  // breaking protocol change even if both dynamic test signers adapt together.
  assert.equal(canonicalNativeOwnershipProofBytes(proof).toString('utf8'),
   canonicalUtf8);
  const sig=Buffer.from(signatureBase64url,'base64url');
  assert.equal(sig.length,64);
  assert.equal(sig.toString('base64url'),signatureBase64url);
  assert.equal(verifyEd25519(null,Buffer.from(canonicalUtf8,'utf8'),key,sig),
   true,'expected independent signature '+proof.purpose);
  assert.equal(verifyStatic(proof,signatureBase64url,key),true);
  assert.equal(verifyEd25519(null,Buffer.from(JSON.stringify(proof),'utf8'),
   key,sig),false,'object-shaped JSON cannot replace the ordered array');
 }
});

test('serialized payload object key order does not affect the exact signed tuple',()=>{
 const key=createPublicKey(fixture.publicKeyPem);
 for(const v of fixture.vectors){
  const permuted=Object.fromEntries(Object.entries(v.proof).reverse());
  assert.notDeepEqual(Object.keys(permuted),FIELDS);
  assert.equal(canonicalNativeOwnershipProofBytes(permuted).toString('utf8'),
   v.canonicalUtf8);
  assert.equal(verifyStatic(permuted,v.signatureBase64url,key),true);
 }
});

test('fixed Ed25519 signatures reject mutations to every signed field, including cross-app purpose and tenant',()=>{
 const key=createPublicKey(fixture.publicKeyPem);
 const mutate={
  version:v=>'duckbio.native-ownership.v2',
  keyId:v=>'unknown-native-key',
  purpose:v=>v==='inspect'?'bind':'inspect',
  nonce:v=>'AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA',
  appId:v=>v==='goflo'?'eel':'goflo',
  workspaceAccountId:v=>v+'-attacker',
  workspaceOrganizationId:v=>v+'-attacker',
  nativeUserId:v=>v+'-attacker',
  nativeOrganizationId:v=>v+'-attacker',
  issuedAt:v=>v+1,
  expiresAt:v=>v+1,
  active:v=>!v,
  ownershipVerified:v=>!v
 };
 assert.deepEqual(Object.keys(mutate),FIELDS);
 for(const v of fixture.vectors){
  for(const field of FIELDS){
   const changed={...v.proof,[field]:mutate[field](v.proof[field])};
   assert.equal(verifyStatic(changed,v.signatureBase64url,key),false,
    v.proof.purpose+' altered '+field);
  }
 }
});

test('fixture public signing key is not bundled as a private credential and all vectors are test-only',()=>{
 assert.match(fixture.description,/PUBLIC SYNTHETIC/);
 assert.match(fixture.description,/NEVER USE/);
 assert.equal(Object.keys(fixture).sort().join(','),
  'description,format,publicKeyPem,vectors');
 assert.equal(fixture.publicKeyPem.includes('PRIVATE KEY'),false);
 for(const v of fixture.vectors){
  assert.deepEqual(Object.keys(v).sort(),
   ['canonicalUtf8','proof','signatureBase64url']);
 }
});
